-- Required environment:
--     - All schema migrations applied (schema.sql + achievements_schema.sql
--       + classes_exam_schema.sql + classes_resources_schema.sql
--       + chatroom.sql + chat_requests.sql + notice_board_schema.sql
--       + profile_feature.sql + classes_migration_2026.sql + fix_*.sql).
--     - Auth users exist. tools/seed.py creates them via the service-role
--       Admin API (auth.admin.create_user) and the handle_new_user trigger
--       auto-creates profiles. The IDs are emitted to /tmp/seed_ids.json.
--
-- Usage:
--     psql "$SUPABASE_DB_URL" \
--         -v seed_ids_json="$(cat /tmp/seed_ids.json)" \
--         -v ON_ERROR_STOP=1 \
--         -f Database/seed.sql
-- =====================================================================

\set ON_ERROR_STOP on

-- ---------------------------------------------------------------------
-- 0. Load the JSON map of auth.users IDs generated by tools/seed.py
-- ---------------------------------------------------------------------
-- psql :'seed_ids_json' substitutes the JSON string as a psql literal.
-- We wrap it in a DO block that validates JSON and stashes it in
-- current_setting('seed.ids', true) so subsequent blocks can read it.
DO $$
DECLARE
    v_json text := current_setting('seed.ids', true);
    v_parsed jsonb;
BEGIN
    IF v_json IS NULL OR v_json = '' THEN
        RAISE EXCEPTION
            'seed.ids is empty. Run: tools/seed.py --out /tmp/seed_ids.json';
    END IF;

    BEGIN
        v_parsed := v_json::jsonb;
    EXCEPTION WHEN others THEN
        RAISE EXCEPTION 'seed.ids is not valid JSON: %', SQLERRM;
    END;

    PERFORM set_config('seed.ids', v_parsed::text, false);
    RAISE NOTICE 'seed.ids loaded: % teachers, % students',
        jsonb_array_length(v_parsed->'teachers'),
        jsonb_array_length(v_parsed->'students');
END $$;

