--   * manual_courses — teachers who already own a REAL course (fetched live
--     by tools/seed.py) keep it as-is; only teachers with none get 2 demo
--     courses each
--   * 25 students (linked to auth.users that already exist)
--   * enrollments (round-robin across the real + demo course pool, so a
--     teacher's real pre-existing course gets students too)
--   * 5–10 course_invite rows
--   * 2 attendance sessions + records, and a midterm/final exam + marks,
--     per course that has enrolled students
--   * 10 projects (skills + author)
--   * 8 certificates (skills)
--   * 10 research papers (5 teacher + 5 student)
--   * 25 advisor rows (one per student)
--   * 3 group chat rooms (with room codes) with members + a few messages
--   * 1 pending chat_request
--   * 8 sample notifications
