-- =====================================================================
-- B. Teachers → instructor rows (idempotent via employee_id)
-- =====================================================================
DO $$
DECLARE
    v_dept_id  INT;
    v_emp_id   TEXT;
    v_uid      UUID;
    v_fname    TEXT;
    v_lname    TEXT;
    v_gender   public.gender_val;
    v_dob      DATE;
    v_phone    TEXT;
    v_desig    public.designation_val;
    v_spec     TEXT;
    v_office   TEXT;
    v_bio      TEXT;
    v_teacher  jsonb;
    v_instr_id INT;
BEGIN
    SELECT dept_id INTO v_dept_id FROM public.department WHERE dept_code = 'CSE';
    IF v_dept_id IS NULL THEN
        RAISE EXCEPTION 'CSE department missing — section A must run first';
    END IF;

    FOR v_teacher IN
        SELECT * FROM jsonb_array_elements(
            current_setting('seed.ids', true)::jsonb->'teachers'
        )
    LOOP
        v_uid    := (v_teacher->>'uid')::UUID;
        v_fname  := v_teacher->>'first_name';
        v_lname  := v_teacher->>'last_name';
        v_gender := (v_teacher->>'gender')::public.gender_val;
        v_dob    := (v_teacher->>'dob')::DATE;
        v_phone  := v_teacher->>'phone';
        v_desig  := (v_teacher->>'designation')::public.designation_val;
        v_spec   := v_teacher->>'specialization';
        v_office := v_teacher->>'office_location';
        v_bio    := v_teacher->>'bio';
        v_emp_id := v_teacher->>'employee_id';

        -- hire_date between 1 and 10 years ago
        INSERT INTO public.instructor (
            profile_id, dept_id, first_name, last_name, gender, date_of_birth,
            phone, employee_id, hire_date, designation, specialization,
            office_location, bio, is_active
        )
        VALUES (
            v_uid, v_dept_id, v_fname, v_lname, v_gender, v_dob,
            v_phone, v_emp_id,
            CURRENT_DATE - (INTERVAL '1 year' + (RANDOM() * INTERVAL '9 years')),
            v_desig, v_spec, v_office, v_bio, TRUE
        )
        ON CONFLICT (employee_id) DO NOTHING
        RETURNING instructor_id INTO v_instr_id;

        IF v_instr_id IS NULL THEN
            SELECT instructor_id INTO v_instr_id
            FROM public.instructor WHERE employee_id = v_emp_id;
        END IF;

        UPDATE public.profiles
        SET instructor_id = v_instr_id,
            first_name    = v_fname,
            last_name     = v_lname,
            phone         = v_phone
        WHERE id = v_uid;
    END LOOP;
END $$;


