-- =====================================================================
-- E. Enrollments — distribute 25 students across the entire course pool
-- =====================================================================
-- The pool is every active manual_course in the DB — any teacher's real,
-- already-created course(s) (however they were made, demo teacher or not)
-- plus the 10 curriculum-based demo courses from Section C. This ensures a
-- real pre-existing course (e.g. one made through the app UI) also gets
-- students, matching "teacher already created a course, add students to it."
-- Round-robin: student i gets pool[i % n] and pool[(i+2) % n], so each
-- course gets students and each student gets 2 courses.
DO $$
DECLARE
    v_courses  INT[];
    v_students INT[];
    v_idx      INT;
    v_student_id INT;
    v_course_id  INT;
BEGIN
    SELECT COALESCE(array_agg(manual_course_id ORDER BY manual_course_id), '{}')
      INTO v_courses
    FROM public.manual_course
    WHERE is_active;

    SELECT COALESCE(array_agg(student_id ORDER BY student_id), '{}')
      INTO v_students
    FROM public.student
    WHERE student_roll BETWEEN '2023715001' AND '2023715025';

    IF array_length(v_courses, 1) IS NULL OR array_length(v_students, 1) IS NULL THEN
        RAISE NOTICE 'No fresh courses or students found — skipping enrollment';
        RETURN;
    END IF;

    FOR v_idx IN 1..array_length(v_students, 1) LOOP
        v_student_id := v_students[v_idx];
        v_course_id  := v_courses[((v_idx - 1) % array_length(v_courses, 1)) + 1];

        INSERT INTO public.manual_enrollment (manual_course_id, student_id, is_active)
        VALUES (v_course_id, v_student_id, TRUE)
        ON CONFLICT (manual_course_id, student_id) DO NOTHING;

        v_course_id  := v_courses[((v_idx + 1) % array_length(v_courses, 1)) + 1];
        INSERT INTO public.manual_enrollment (manual_course_id, student_id, is_active)
        VALUES (v_course_id, v_student_id, TRUE)
        ON CONFLICT (manual_course_id, student_id) DO NOTHING;
    END LOOP;
END $$;


-- =====================================================================
-- E2. Classes: attendance sessions/records + exams/marks per course
-- =====================================================================
-- For every course that has enrolled students (real or demo), create a
-- couple of attendance sessions with per-student records, plus a midterm
-- and final exam with per-student marks — so teacher dashboards ("classes")
-- have real data to show.
DO $$
DECLARE
    v_course       RECORD;
    v_student_id   INT;
    v_session_id   INT;
    v_exam_id      INT;
    v_marks        NUMERIC;
    v_total        NUMERIC;
    v_grade        TEXT;
    v_points       NUMERIC;
    v_created_by   UUID;
    v_topics       TEXT[] := ARRAY['Introduction & Overview','Core Concepts','Problem Solving Session'];
    v_i            INT;
BEGIN
    FOR v_course IN
        SELECT mc.manual_course_id, mc.course_name, mc.credit_hours, mc.semester,
               mc.academic_year, i.profile_id AS instructor_profile_id
        FROM public.manual_course mc
        JOIN public.instructor i ON i.instructor_id = mc.instructor_id
        WHERE EXISTS (
            SELECT 1 FROM public.manual_enrollment me
            WHERE me.manual_course_id = mc.manual_course_id AND me.is_active
        )
    LOOP
        v_created_by := v_course.instructor_profile_id;
        IF v_created_by IS NULL THEN CONTINUE; END IF;

        -- Idempotency: skip courses that already have seeded sessions/exams
        IF EXISTS (SELECT 1 FROM public.attendance_session s WHERE s.manual_course_id = v_course.manual_course_id)
           OR EXISTS (SELECT 1 FROM public.exam e WHERE e.manual_course_id = v_course.manual_course_id) THEN
            CONTINUE;
        END IF;

        -- 2 attendance sessions
        FOR v_i IN 1..2 LOOP
            INSERT INTO public.attendance_session (
                manual_course_id, instructor_id, session_date, session_title, topic
            )
            SELECT v_course.manual_course_id, mc.instructor_id,
                   CURRENT_DATE - (7 * (3 - v_i)),
                   'Class Session ' || v_i,
                   v_topics[v_i]
            FROM public.manual_course mc WHERE mc.manual_course_id = v_course.manual_course_id
            RETURNING session_id INTO v_session_id;

            INSERT INTO public.attendance_record (session_id, student_id, status)
            SELECT v_session_id, me.student_id,
                   CASE WHEN RANDOM() < 0.85 THEN 'Present'
                        WHEN RANDOM() < 0.6 THEN 'Late'
                        ELSE 'Absent' END
            FROM public.manual_enrollment me
            WHERE me.manual_course_id = v_course.manual_course_id AND me.is_active;
        END LOOP;

        -- Midterm + Final exams
        FOR v_i IN 1..2 LOOP
            v_total := CASE WHEN v_i = 1 THEN 30 ELSE 50 END;
            INSERT INTO public.exam (
                manual_course_id, exam_name, exam_type, total_marks, credit_hours,
                exam_date, semester, academic_year, description, is_published, created_by
            )
            VALUES (
                v_course.manual_course_id,
                v_course.course_name || CASE WHEN v_i = 1 THEN ' - Midterm' ELSE ' - Final' END,
                CASE WHEN v_i = 1 THEN 'Midterm' ELSE 'Final' END,
                v_total, v_course.credit_hours,
                CURRENT_DATE - (30 * (3 - v_i)),
                v_course.semester, v_course.academic_year,
                'Demo exam for ' || v_course.course_name,
                TRUE, v_created_by
            )
            RETURNING exam_id INTO v_exam_id;

            FOR v_student_id IN
                SELECT me.student_id FROM public.manual_enrollment me
                WHERE me.manual_course_id = v_course.manual_course_id AND me.is_active
            LOOP
                v_marks := ROUND((v_total * (0.60 + RANDOM() * 0.35))::NUMERIC, 2);
                v_grade := CASE
                    WHEN v_marks >= v_total * 0.90 THEN 'A+'
                    WHEN v_marks >= v_total * 0.80 THEN 'A'
                    WHEN v_marks >= v_total * 0.70 THEN 'A-'
                    WHEN v_marks >= v_total * 0.60 THEN 'B'
                    ELSE 'C'
                END;
                v_points := CASE v_grade
                    WHEN 'A+' THEN 4.00 WHEN 'A' THEN 3.75 WHEN 'A-' THEN 3.50
                    WHEN 'B' THEN 3.00 ELSE 2.50
                END;

                INSERT INTO public.exam_mark (
                    exam_id, student_id, marks_obtained, grade, grade_points, entered_by
                )
                VALUES (v_exam_id, v_student_id, v_marks, v_grade, v_points, v_created_by)
                ON CONFLICT (exam_id, student_id) DO NOTHING;
            END LOOP;
        END LOOP;
    END LOOP;
END $$;


